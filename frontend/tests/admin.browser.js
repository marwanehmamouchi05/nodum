// Real HTTP QA against tests/admin_qa_server.py's temporary SQLite fixture.
// No audited runtime DB, real provider, or real hardware is used.
async (page) => {
  const results = []
  const base = 'http://127.0.0.1:8766'
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const navigation = name => page.getByRole('navigation').getByRole('button', { name, exact: true })
  const section = name => page.locator('section').filter({ has: page.getByRole('heading', { name, exact: true }) })
  const requests = []
  const listener = request => { if (request.url().startsWith(base)) requests.push(new URL(request.url()).pathname) }
  page.on('request', listener)
  try {
    await page.goto('http://127.0.0.1:5174/#Admin/Setup')
    await page.evaluate(async base => {
      const session = await fetch(base + '/auth/session', { credentials: 'include' }).then(r => r.json())
      const response = await fetch(base + '/auth/login', { method: 'POST', credentials: 'include', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': session.csrf_token }, body: JSON.stringify({ username: 'qa-admin', password: 'Synthetic-local-QA-only' }) })
      if (!response.ok) throw new Error('Synthetic login failed')
    }, base)
    await page.reload()
    await page.getByRole('heading', { name: 'Welcome to Nodum', exact: true }).waitFor()
    check(!requests.some(p => /appointments|emergencies|building\/catalog|ring\/.*events/.test(p)), 'Admin must not fetch operational resources')
    results.push('Empty Admin workspace makes no operational data requests')
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Empty overflow at ' + width)
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.evaluate(() => { document.activeElement?.blur(); scrollTo(0, 0) })
    await page.screenshot({ path: 'C:/dev/nodum/docs/qa/admin-empty-1440.png', fullPage: true, animations: 'disabled', timeout: 15000 })
    await page.setViewportSize({ width: 390, height: 1000 })
    await page.screenshot({ path: 'C:/dev/nodum/docs/qa/admin-empty-390.png', fullPage: true, animations: 'disabled', timeout: 15000 })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Load synthetic demo building', exact: true }).click()
    await page.getByRole('heading', { name: 'Nodum Administration', exact: true }).waitFor()
    check(await page.getByText('Synthetic demo', { exact: true }).count() === 1, 'Demo must be labeled')
    const state = await page.evaluate(async base => {
      const catalog = await fetch(base + '/structure/catalog', { credentials: 'include' }).then(r => r.json())
      const accounts = await fetch(base + '/admin/accounts', { credentials: 'include' }).then(r => r.json())
      return { nodes: catalog.nodes, accounts }
    }, base)
    check(state.nodes.filter(n => n.kind === 'floor').length === 6, 'Reference floors missing')
    check(state.nodes.filter(n => n.kind === 'unit').length === 10, 'Reference units missing')
    check(state.accounts.length === 1, 'Demo must not create accounts')
    results.push('Explicit demo creates only synthetic reference configuration')
    await navigation('Building').click()
    await page.getByLabel('Space type', { exact: true }).selectOption('location')
    await section('Add a space').getByLabel('Name', { exact: true }).fill('Synthetic QA service area')
    await section('Add a space').getByLabel('Located in', { exact: true }).selectOption({ label: 'Ground Floor' })
    await section('Add a space').getByLabel('Area designation', { exact: true }).selectOption('restricted')
    await section('Add a space').getByRole('button', { name: 'Add space', exact: true }).click()
    await page.getByText('Synthetic QA service area', { exact: true }).first().waitFor()
    await page.reload()
    await page.getByText('Synthetic QA service area', { exact: true }).first().waitFor()
    results.push('Configured hierarchy persists after reload')
    await navigation('Hardware').click()
    await page.getByLabel('Device name', { exact: true }).fill('Synthetic QA sensor')
    await page.getByLabel('Device type', { exact: true }).selectOption('sensor')
    await page.getByLabel('Integration', { exact: true }).selectOption({ index: 1 })
    await page.getByRole('button', { name: 'Register device', exact: true }).click()
    await page.getByRole('heading', { name: 'Synthetic QA sensor', exact: true }).waitFor()
    const hardware = page.locator('.admin-hardware').filter({ has: page.getByRole('heading', { name: 'Synthetic QA sensor', exact: true }) })
    check(await hardware.getByText('Location: Needs assignment', { exact: true }).count() === 1, 'Unassigned device must be explicit')
    await hardware.getByLabel('Location', { exact: true }).selectOption({ label: 'Synthetic QA service area' })
    await hardware.getByRole('button', { name: 'Save assignment', exact: true }).click()
    await page.getByText('Location: Synthetic QA service area', { exact: true }).waitFor()
    check(await page.getByRole('button', { name: /^(Unlock|Lock|View stream|Call elevator)$/ }).count() === 0, 'Unsupported hardware actions must be absent')
    results.push('Unassigned device is mapped securely; no fake capabilities')
    await navigation('Accounts').click()
    await page.getByLabel('Full name', { exact: true }).fill('Synthetic QA Resident')
    await page.getByLabel('Login name', { exact: true }).fill('qa-resident')
    await page.getByLabel('Initial password (12–128 characters)', { exact: true }).fill('Synthetic-QA-resident-only')
    await page.getByLabel('Building, unit, business, or area', { exact: true }).selectOption({ label: 'Apartment 101' })
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.getByText('Synthetic QA Resident', { exact: true }).first().waitFor()
    const affiliation = section('Assign a unit, business, or work area')
    await affiliation.getByLabel('Account', { exact: true }).selectOption({ label: 'Synthetic QA Resident' })
    await affiliation.getByLabel('Affiliation', { exact: true }).selectOption('resident')
    await affiliation.getByLabel('Unit, business, building, or area', { exact: true }).selectOption({ label: 'Apartment 101' })
    await affiliation.getByRole('button', { name: 'Save affiliation', exact: true }).click()
    await navigation('Roles & Permissions').click()
    await page.getByLabel('Applies to', { exact: true }).selectOption({ label: 'Apartment 101' })
    await page.getByLabel('Role', { exact: true }).selectOption('resident')
    await page.getByRole('checkbox', { name: 'View building structure', exact: true }).waitFor()
    await page.getByLabel('Account', { exact: true }).selectOption({ label: 'Synthetic QA Resident' })
    await page.getByRole('checkbox', { name: 'View building structure', exact: true }).check()
    await page.getByRole('button', { name: 'Save role assignment', exact: true }).click()
    await page.getByText('Resident · Synthetic QA Resident', { exact: true }).waitFor()
    check(await page.getByRole('checkbox', { name: 'View permitted camera content', exact: true }).count() === 0, 'Admin must not delegate unavailable camera authority')
    results.push('Account, affiliation, and permission assignment remain separate')
    await navigation('Setup').click()
    await page.getByRole('button', { name: '4. Device Mapping', exact: true }).click()
    await page.getByText('Current step: Device Mapping · Saved to Nodum', { exact: true }).waitFor()
    await page.reload()
    await page.getByText('Current step: Device Mapping · Saved to Nodum', { exact: true }).waitFor()
    await navigation('Policies').click()
    await page.getByRole('button', { name: 'Mark boundaries reviewed', exact: true }).click()
    await page.getByRole('button', { name: 'Policy boundaries reviewed', exact: true }).waitFor()
    await navigation('System & Audit').click()
    await page.getByRole('button', { name: 'Finish configuration setup', exact: true }).click()
    await page.getByRole('button', { name: 'Setup completed', exact: true }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: 'Setup completed', exact: true }).waitFor()
    results.push('Onboarding progress and completion survive reload')
    for (const name of ['Setup', 'Building', 'Hardware', 'Integrations', 'Accounts', 'Roles & Permissions', 'Policies', 'System & Audit']) {
      await navigation(name).click()
      for (const width of [1440, 768, 390]) {
        await page.setViewportSize({ width, height: 1000 })
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), name + ' overflows at ' + width)
      }
    }
    results.push('All 8 Admin screens pass 1440/768/390 overflow checks')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await navigation('Building').click()
    await page.evaluate(() => { document.activeElement?.blur(); scrollTo(0, 0) })
    await page.screenshot({ path: 'C:/dev/nodum/docs/qa/admin-building-1440.png', fullPage: true, animations: 'disabled', timeout: 15000 })
    await navigation('Hardware').click()
    await page.screenshot({ path: 'C:/dev/nodum/docs/qa/admin-hardware-1440.png', fullPage: true, animations: 'disabled', timeout: 15000 })
    await page.setViewportSize({ width: 390, height: 1000 })
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: 'C:/dev/nodum/docs/qa/admin-hardware-390.png', fullPage: true, animations: 'disabled', timeout: 15000 })
    await page.keyboard.press('Tab')
    check(await page.evaluate(() => { const e = document.activeElement; return ['A', 'BUTTON', 'INPUT', 'SELECT'].includes(e.tagName) && getComputedStyle(e).outlineStyle !== 'none' }), 'Keyboard focus must be visible')
    results.push('Keyboard focus visible; form controls and status labels semantic')
    await page.route(base + '/structure/catalog', route => route.fulfill({ status: 403, json: { detail: 'Synthetic permission failure' } }))
    await page.getByRole('button', { name: 'Refresh', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Configuration is unavailable' }).waitFor()
    check(await page.getByText('Synthetic QA sensor', { exact: true }).count() === 0, 'Failed refresh must clear records')
    await page.unroute(base + '/structure/catalog')
    await page.getByRole('button', { name: 'Try again', exact: true }).click()
    await page.getByRole('heading', { name: 'Synthetic QA sensor', exact: true }).waitFor()
    results.push('Permission/API failure clears stale records and retry recovers')
    return { results, assertions: results.length, providerCalls: 0, auditedDatabaseWrites: 0 }
  } finally { page.off('request', listener) }
}
